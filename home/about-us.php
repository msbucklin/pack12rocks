<h2>&nbsp;</h2>

<h2>Why we say, "Pack 12 Rocks!"</h2>

<p><strong>Who We Are</strong></p>

<ul>
	<li>Cub Scout Pack 12 proudly serves boys &amp; girls of Clayton and Baldwin Elementary Schools in Southwest Austin, as well as the surrounding area.</li>
	<li>The Pack is chartered by the Circle C Ranch HOA and is part of the Scouts BSA (Boy Scouts of America) - Capitol Area Council - Thunderbird District.&nbsp;&nbsp;</li>
</ul>

<p><strong>Our Goal</strong></p>

<ul>
	<li>Pack 12 provides opportunities for youth development through outdoor activities, community service, family-centered events, and physical fitness. We maintain a fun and safe environment that teaches our children the values and skills they need to grow into tomorrow’s leaders.</li>
	<li>We know that parents have many choices for after-school activities and we believe that Scouting offers one of the most exciting and rewarding programs available to your family. Join us and see why we say that PACK 12 ROCKS!</li>
</ul>

<p><strong>What We Do</strong></p>

<ul>
	<li>Camping, hiking, archery, knot-tying, fishing, fire-building, sports, geocaching, model car racing, woodworking, community service, and much more!</li>
</ul>

<p><strong>Who Can Participate</strong></p>

<ul>
	<li>Boys and girls in Kindergarten through 5th grade can join Pack 12 Cub Scouts</li>
	<li>You can begin your journey at any grade level</li>
	<li>Mom and Dad can be leaders or help behind the scenes</li>
	<li>Cub Scouts are family focused. Siblings are welcome to participate too. It’s fun for the entire family!&nbsp;</li>
</ul>

<p><strong>Time Commitment</strong></p>

<ul>
	<li>You will have up to three meetings a month (one for the Pack and one to two for your small group, or “Den”).</li>
	<li>Camping and overnight trips are typically three times a year</li>
	<li>Other activities are also planned throughout the year - including over the summer!</li>
</ul>

<p><strong>Cost</strong></p>

<ul>
	<li>Expect a yearly cost of approximately $250 to cover your national dues, local pack dues, uniform&nbsp;and handbook</li>
	<li>Some activities, like campout or winter lock-in may have additional costs if your family participates</li>
	<li>Two fundraising sales are also held annually to help pay for pack awards and activities</li>
</ul>

<p><strong>Scouting Means Doing</strong></p>

<ul>
	<li>When you sign your child up for Cub Scouting, you are signing up for more than an after-school activity. Whether it’s camping for the first time or catching that first fish, your child will be taking part in activities that are fun as well as character building.</li>
	<li>We camp twice a year and have a winter trip to places like the USS Lexington, NASA, and Perot Childrens Museum.</li>
	<li>Our Pack contributes to the community through hands-on community service projects. Helping other people is a fundamental part of the Scouting experience.</li>
</ul>

<p><strong>Scouting Needs Leaders</strong></p>

<ul>
	<li>We are a 100% volunteer-run organization and rely on the dedication of our leaders to provide a meaningful and worthwhile program for your family.</li>
	<li>Volunteer roles range from behind-the-scenes to hands-on with our scouts.</li>
</ul>

<p><strong>More Questions?&nbsp;</strong></p>

<ul>
	<li>More information can be found in the&nbsp;<a href="https://drive.google.com/file/d/14YcZ-jeLZhaPUhD1r7Wg81qPBWMoyOce/view?usp=sharing" target="_blank"><strong>Pack 12 Handbook</strong></a></li>
	<li>You can reach out to&nbsp;contact us&nbsp;anytime.</li>
</ul>

<p><strong>Ready to run with the Pack?</strong></p>

<ul>
	<li>Complete the <a href="https://my.scouting.org/VES/OnlineReg/1.0.0/?tu=UF-MB-564paa0012">Online Registration</a> to get started with the Pack.</li>
</ul>
